/**
 * 커밋 메시지 규칙을 검사한다. 규칙은 CONTRIBUTING.md 2절.
 *
 * 셸 스크립트 대신 Node로 작성해 맥·윈도우에서 같은 방식으로 동작한다.
 */
import { readFileSync } from "node:fs";

const TYPES = ["feat", "fix", "docs", "style", "refactor", "test", "chore"];
const TITLE = new RegExp(`^(${TYPES.join("|")}): .+ #\\d+( #\\d+)*$`);
const CO_AUTHOR = /^\s*co-authored-by:/im;
const AI_SIGNATURE = /^\s*(🤖\s*)?generated with /im;

const messagePath = process.argv[2];
const message = readFileSync(messagePath, "utf8")
  .split("\n")
  // git이 붙이는 안내 주석 줄은 실제 메시지가 아니다.
  .filter((line) => !line.startsWith("#"))
  .join("\n")
  .trim();
const title = message.split("\n")[0];

// git이 자동으로 만드는 머지·되돌리기 커밋은 형식 검사에서 뺀다.
const isAutoGenerated = /^(Merge |Revert ")/.test(title);

const errors = [];

if (CO_AUTHOR.test(message)) {
  errors.push("Co-Authored-By 줄은 넣지 않는다.");
}
if (AI_SIGNATURE.test(message)) {
  errors.push('AI 도구의 자동 서명("Generated with ...")은 넣지 않는다.');
}
if (!isAutoGenerated && !TITLE.test(title)) {
  errors.push(
    `첫 줄은 "타입: 작업 내용 #이슈번호" 형식이어야 한다. (타입: ${TYPES.join(", ")})`,
    "예: feat: 문의 폼 서버 검증 추가 #12",
  );
}

if (errors.length > 0) {
  console.error("\n커밋 메시지 규칙 위반:");
  for (const error of errors) console.error(`  - ${error}`);
  console.error(`\n지금 메시지 첫 줄: ${title || "(비어 있음)"}\n`);
  process.exit(1);
}
