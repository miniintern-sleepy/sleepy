/**
 * 커밋·PR 규칙. 커밋 훅(scripts/hooks)과 CI(scripts/ci)가 같이 쓴다.
 * 규칙을 바꾸면 CONTRIBUTING.md도 함께 고친다.
 */

export const TYPES = [
  "feat",
  "fix",
  "docs",
  "style",
  "refactor",
  "test",
  "chore",
];

const TYPE_GROUP = `(${TYPES.join("|")})`;
const WORK_TITLE = new RegExp(`^${TYPE_GROUP}: .+ #\\d+( #\\d+)*$`);
const RELEASE_TITLE = /^release: v\d+\.\d+\.\d+ .+$/;
const WORK_BRANCH = new RegExp(`^${TYPE_GROUP}/\\d+-[a-z0-9-]+$`);
const CO_AUTHOR = /^\s*co-authored-by:/im;
const AI_SIGNATURE = /^\s*(🤖\s*)?generated with /im;
const CLOSES_ISSUE = /\b(close[sd]?|fix(e[sd])?|resolve[sd]?) #\d+/i;

/** git이 자동으로 만드는 머지·되돌리기 커밋인지. 형식 검사에서 뺀다. */
function isAutoGenerated(title) {
  return /^(Merge |Revert ")/.test(title);
}

/** Co-Authored-By 줄과 AI 도구 자동 서명을 찾는다. 커밋 메시지와 PR 본문에 같이 쓴다. */
export function findSignatureErrors(text) {
  const errors = [];
  if (CO_AUTHOR.test(text)) errors.push("Co-Authored-By 줄은 넣지 않는다.");
  if (AI_SIGNATURE.test(text)) {
    errors.push('AI 도구의 자동 서명("Generated with ...")은 넣지 않는다.');
  }
  return errors;
}

/**
 * 커밋 메시지 하나를 검사한다.
 *
 * @returns 위반 내용 목록. 비어 있으면 통과
 */
export function checkCommitMessage(message) {
  const title = message.split("\n")[0];
  const errors = findSignatureErrors(message);
  if (!isAutoGenerated(title) && !WORK_TITLE.test(title)) {
    errors.push(
      `첫 줄은 "타입: 작업 내용 #이슈번호" 형식이어야 한다. (타입: ${TYPES.join(", ")})`,
      "예: feat: 문의 폼 서버 검증 추가 #12",
    );
  }
  return errors;
}

/**
 * PR 제목·브랜치·본문을 검사한다. 커밋은 checkCommitMessage로 따로 검사한다.
 *
 * 작업 PR(→ dev)과 배포 PR(dev → main)의 규칙이 다르다.
 * @returns 위반 내용 목록. 비어 있으면 통과
 */
export function checkPullRequest({ title, body, headRef, baseRef }) {
  const errors = findSignatureErrors(body ?? "").map((e) => `PR 본문: ${e}`);

  if (baseRef === "main") {
    if (headRef !== "dev") errors.push("main으로는 dev에서만 PR을 올린다.");
    if (!RELEASE_TITLE.test(title)) {
      errors.push(
        '배포 PR 제목은 "release: v버전 내용" 형식이어야 한다.',
        "예: release: v0.2.0 문의 기능",
      );
    }
    return errors;
  }

  if (!WORK_TITLE.test(title)) {
    errors.push(
      `PR 제목은 "타입: 작업 내용 #이슈번호" 형식이어야 한다. (타입: ${TYPES.join(", ")})`,
    );
  }
  if (!WORK_BRANCH.test(headRef)) {
    errors.push(
      `브랜치 이름은 "타입/이슈번호-설명" 형식이어야 한다. 예: feat/12-contact-form (지금: ${headRef})`,
    );
  }
  if (!CLOSES_ISSUE.test(body ?? "")) {
    errors.push('PR 본문에 "Closes #이슈번호"가 있어야 한다.');
  }
  return errors;
}
